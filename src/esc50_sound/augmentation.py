"""Training-only waveform augmentation for pinned ESC-50 log-mel experiments.

Never use this module to modify validation, test, cache, or inference features.
The random draws use PyTorch's global generator so epoch-boundary RNG snapshots
cover Gaussian noise, SNR, mixing decisions and partner permutation.
"""
from __future__ import annotations

import hashlib
import io
import json
import math
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import TensorDataset

from .audio import FRONTEND, log_mel, read_audio
from .data import read_metadata
from .quality import cache_metadata_contract, metadata_contract
from .records import sha256


def validate_augmentation(probability: float, min_db: float, max_db: float, mixup_alpha: float) -> None:
    vals = (probability, min_db, max_db, mixup_alpha)
    if any(isinstance(v, bool) or not isinstance(v, (float, int)) or not math.isfinite(v) for v in vals):
        raise ValueError("Augmentation settings must be finite numbers")
    if not 0 <= probability <= 1:
        raise ValueError("noise_probability must be between 0 and 1")
    if not -20 <= min_db <= max_db <= 80:
        raise ValueError("Noise SNR range must be within [-20, 80] dB and ordered")
    if not 0 <= mixup_alpha <= 10:
        raise ValueError("mixup_alpha must be in [0, 10]; 0 disables waveform Mixup")


def augmentation_config(args) -> dict:
    values = dict(noise_probability=getattr(args, "noise_probability", 0.0),
                  noise_snr_min_db=getattr(args, "noise_snr_min_db", 10.0),
                  noise_snr_max_db=getattr(args, "noise_snr_max_db", 30.0),
                  mixup_alpha=getattr(args, "mixup_alpha", 0.0),
                  raw_audio_root=getattr(args, "raw_audio_root", "data/ESC-50"))
    validate_augmentation(values["noise_probability"], values["noise_snr_min_db"],
                          values["noise_snr_max_db"], values["mixup_alpha"])
    if not isinstance(values["raw_audio_root"], str) or not values["raw_audio_root"].strip():
        raise ValueError("raw_audio_root must be a nonempty path")
    return values


def enabled(cfg: dict) -> bool:
    return cfg["noise_probability"] > 0 or cfg["mixup_alpha"] > 0


def verify_waveform_sources(cache: dict, cache_path: str | Path, train_ids: list[int], root: str | Path, *, load_waveforms: bool = False):
    """Load and verify only *training* WAVs; reject stale or unaudited cache inputs.

    Pinned source hashes are generated by `esc50 prepare` (schema v2).
    Full feature equality is checked before augmentation, so we cannot silently
    mix raw audio from one source with labels/features from another cache.
    """
    root, cache_path = Path(root), Path(cache_path)
    sidecar = json.loads(Path(str(cache_path) + ".json").read_text())
    hashes = sidecar.get("audio_file_sha256")
    if sidecar.get("schema_version") != 2 or not isinstance(hashes, dict):
        raise ValueError("Waveform augmentation requires a v2 cache with pinned WAV SHA-256; rerun prepare")
    metadata_file = root / "meta" / "esc50.csv"
    if not metadata_file.is_file() or sidecar.get("metadata_sha256") != sha256(metadata_file):
        raise ValueError("Raw WAV root metadata does not match the feature cache")
    rows = read_metadata(root)
    if not metadata_contract(rows)["valid"] or not cache_metadata_contract(cache, rows)["valid"]:
        raise ValueError("Cache and original metadata disagree")
    import soundfile as sf
    waveforms = []
    for idx in train_ids:
        name = str(cache["names"][idx])
        path = root / "audio" / name
        if name not in hashes or not path.is_file():
            raise ValueError(f"Missing or modified training WAV: {name}")
        # Verify the exact immutable bytes also used for decoding: no TOCTOU gap.
        raw_bytes = path.read_bytes()
        if hashlib.sha256(raw_bytes).hexdigest() != hashes[name]:
            raise ValueError(f"Missing or modified training WAV: {name}")
        info = sf.info(io.BytesIO(raw_bytes))
        if info.samplerate != 44100 or info.channels != 1 or info.frames != 5 * 44100:
            raise ValueError(f"Invalid official WAV format: {name}")
        if load_waveforms:
            waveform = read_audio(io.BytesIO(raw_bytes))
            clean_feature = log_mel(waveform)
            if not torch.allclose(clean_feature, torch.from_numpy(cache["x"][idx]), rtol=0, atol=1e-5):
                raise ValueError(f"Waveform and cached features disagree: {name}")
            waveforms.append(waveform)
    if load_waveforms:
        return TensorDataset(torch.stack(waveforms), torch.from_numpy(cache["y"][train_ids]).long())
    return {"checked_training_files": len(train_ids), "source": "only train WAVs",
            "metadata_sha256": sha256(metadata_file)}


def load_training_waveforms(cache: dict, cache_path: str | Path, train_ids: list[int], root: str | Path):
    return verify_waveform_sources(cache, cache_path, train_ids, root, load_waveforms=True)


def add_gaussian_noise(waveforms: torch.Tensor, probability: float, min_db: float, max_db: float) -> torch.Tensor:
    """Add zero-mean Gaussian noise at per-example *added-noise* SNR.

    Original recording's unknown ambient noise is not part of the SNR estimate.
    Silence remains silent; no clipping/renormalization alters requested SNR.
    """
    if probability == 0:
        return waveforms
    if waveforms.ndim != 2 or waveforms.shape[1] != FRONTEND["sample_rate"] * FRONTEND["seconds"]:
        raise ValueError("Expected [batch, 80000] waveform")
    result = waveforms.clone()
    mask = torch.rand((len(waveforms),), device=waveforms.device) < probability
    if not mask.any():
        return result
    selected = result[mask]
    signal_rms = selected.square().mean(dim=1, keepdim=True).sqrt()
    noise = torch.randn_like(selected)
    noise = noise - noise.mean(dim=1, keepdim=True)
    noise_rms = noise.square().mean(dim=1, keepdim=True).sqrt().clamp_min(1e-12)
    snr = torch.empty((len(selected), 1), device=selected.device).uniform_(min_db, max_db)
    amplitude = signal_rms / noise_rms * torch.pow(10.0, -snr / 20.0)
    result[mask] = selected + amplitude * noise
    return result


def mix_waveforms(waveforms: torch.Tensor, targets: torch.Tensor, alpha: float):
    """Waveform Mixup; return (mixed, partner_targets, lambda) for soft CE."""
    if alpha == 0 or len(waveforms) < 2:
        return waveforms, targets, None
    lam = torch.distributions.Beta(alpha, alpha).sample((len(waveforms),)).to(waveforms.device)
    perm = torch.randperm(len(waveforms), device=waveforms.device)
    mixed = lam[:, None] * waveforms + (1.0 - lam[:, None]) * waveforms[perm]
    return mixed, targets[perm], lam


def log_mel_batch(waveforms: torch.Tensor) -> torch.Tensor:
    """Batched version of the checkpoint-compatible frontend; [B,80000]->[B,1,64,313]."""
    if (waveforms.ndim != 2 or waveforms.shape[1] != 80000 or
            waveforms.dtype != torch.float32 or not torch.isfinite(waveforms).all()):
        raise ValueError("Expected finite float32 waveforms [B,80000]")
    window = torch.hann_window(512, device=waveforms.device)
    power = torch.stft(waveforms, 512, 256, window=window, center=True, return_complex=True).abs().square()
    mel_max = 2595 * math.log10(1 + 8000 / 700)
    points = torch.linspace(0, mel_max, 66, device=waveforms.device)
    hz = 700 * (10 ** (points / 2595) - 1)
    freq = torch.linspace(0, 8000, 257, device=waveforms.device)
    left = (freq[None] - hz[:-2, None]) / (hz[1:-1, None] - hz[:-2, None])
    right = (hz[2:, None] - freq[None]) / (hz[2:, None] - hz[1:-1, None])
    filters = torch.minimum(left, right).clamp_min(0)
    return (filters @ power).clamp_min(1e-10).log().unsqueeze(1)
